def load(p):
    t = io.open(p, encoding="utf-8-sig").read()
    t = re.sub(r"//[^\n]*", "", t)
    t = re.sub(r",(\s*[}\]])", r"\1", t)
    return json.loads(t)


def looks():
    """(name, sex, renderables) for every in-game mechanic, plus the player's own."""
    out = []
    d = load(os.path.join(GAME, "Survival", "Character", "CharacterSets",
                          "npc_mechanics.json"))
    for c in d["characters"]:
        sex = "female" if "female" in c["name"] else "male"
        out.append((c["name"], sex, list(c["renderables"])))

    # Data/Character/CharacterSets/default.json is what the game dresses the
    # PLAYER in -- the classic mechanic. A bot wearing it is wearing exactly what
    # a real player's character is built from.
    p = load(os.path.join(GAME, "Data", "Character", "CharacterSets",
                          "default.json"))
    out.append(("classic", "male", list(p["characters"][0]["renderables"])))
    return out


