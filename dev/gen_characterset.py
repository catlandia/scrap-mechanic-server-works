def main():
    got = looks()
    assert len(got) <= len(UUIDS), f"{len(got)} looks but only {len(UUIDS)} uuids"

    entries = []
    for i, (name, sex, rends) in enumerate(got):
        body = ",\n".join(f'\t\t\t\t"{r}"' for r in rends)
        entries.append(ENTRY.format(rends=body, uuid=UUIDS[i], name=name))

    text = HEADER + "{\n\t\"characters\" :\n\t[\n" + ",\n".join(entries) + "\n\t]\n}\n"
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(text)

    print(f"wrote {len(got)} looks to {os.path.relpath(OUT, ROOT)}")
    for i, (name, sex, rends) in enumerate(got):
        print(f"  {UUIDS[i]}  sw_crowd_{name:16} {sex:7} {len(rends)} renderables")

    # The uuid list Crowd.lua needs, ready to paste.
    print("\nCrowd.BOT_UUIDS = {")
    for i, (name, _, _) in enumerate(got):
        print(f'\t"{UUIDS[i]}",   -- {name}')
    print("}")


if __name__ == "__main__":
    main()
