"""Generate the crowd bot character set from vanilla's own in-game mechanics.

WHY THIS EXISTS, AND WHY THE FIRST DESIGN WAS WRONG
---------------------------------------------------

The bots used to be ONE characterset entry, dressed at runtime by
`character:overrideRenderableList( ... )` with a list assembled per bot. It gave
enormous variety and it cost the earth:

    0 bots   60.0 fps    233 bodies   714 shapes
    10 bots  15.0 fps    256 bodies   737 shapes
    20 bots   8   fps

Twenty-three extra bodies do not cost forty-five frames. The controlled
comparison was already in the logs: an earlier 95-bot run held **30 fps** while
the appearance code was throwing (every bot fell back to the characterset's own
outfit and therefore shared one renderable set). Working appearance, 20 bots,
8 fps. Broken appearance, 95 bots, 30 fps. The costume system was the load.

And vanilla says the same thing twice over:

  * `overrideRenderableList` is called in exactly ONE script in the whole game,
    for ONE quest NPC (GenericBuilderQuestCharacter).
  * vanilla's ten different-looking mechanics are ten CHARACTERSET ENTRIES, each
    with a fixed renderable list.

A fixed list per entry is loaded once and shared by every character using it. A
bespoke list per character is not shareable, and twenty of them is twenty sets of
meshes and textures the renderer cannot batch.

So the variety moves into the characterset, exactly as vanilla does it, and the
runtime does nothing but set a name tag.

Usage:  python dev/gen_characterset.py
"""
